def material_default_label(assumptions) -> str | None:
    parts = []
    for item in assumptions:
        value = item.default_value.get("value")
        if item.parameter_code.endswith("_DIAMETER_MM") and value is not None:
            parts.append(f"Ø{value}")
        elif item.value_type == "ENUM" and value is not None:
            parts.append(str(value))
    return " ".join(parts) or None


def effective_material_name(code: str, label: str, assumptions) -> str:
    base = MATERIAL_NAMES.get(code, label)
    detail = material_default_label(assumptions)
    return f"{base} {detail}" if detail else base


