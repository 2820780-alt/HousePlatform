def foundation_comparison(technologies: tuple, requested: list[str], scenario: str) -> dict:
    """Resolve stable editorial profiles only against currently public technology rows."""
    options = [row["technology"] for row in technologies
               if row["technology"].technology_code in _PROFILE]
    by_code = {item.technology_code: item for item in options}
    selected = [code for code in requested if code]
    if not requested:
        selected = [code for code in ("FND_STRIP_MONOLITHIC_RC", "FND_SLAB_MONOLITHIC_RC") if code in by_code]
    valid = len(selected) in (2, 3) and len(set(selected)) == len(selected) and all(code in by_code for code in selected)
    scenario = scenario if scenario in SCENARIOS else ""
    priority = SCENARIOS[scenario][1] if scenario else ()
    criteria = sorted(CRITERIA, key=lambda item: priority.index(item[0]) if item[0] in priority else len(priority))
    return {
        "options": options, "selected": selected, "scenario": scenario,
        "scenarios": SCENARIOS, "error": None if valid else "Выберите две или три разные опубликованные технологии.",
        "columns": [{"technology": by_code[code], "profile": _PROFILE[code]} for code in selected] if valid else [],
        "criteria": criteria,
    }
